package core

import (
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
	"testing"
)

// The frontend calls the bound App methods through a Proxy, so a typo or a
// wrong number of arguments only shows when someone clicks. This test keeps
// frontend/src/backend.d.ts (used by the JavaScript type check) in step
// with the Go methods. Run with YACM_UPDATE_TYPES=1 to rewrite the file.

func tsType(t reflect.Type) string {
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		return tsType(t.Elem()) + "[]"
	case reflect.Map:
		return "Record<string, any>"
	case reflect.Pointer:
		return tsType(t.Elem()) + " | null"
	}
	return "any"
}

func backendTypes() string {
	var b strings.Builder
	b.WriteString("// Generated by apitypes_test.go from the Go App methods; do not edit.\n")
	b.WriteString("// Update: YACM_UPDATE_TYPES=1 go test -run TestBackendTypes .\n\n")
	b.WriteString("export interface Backend {\n")
	at := reflect.TypeOf(&App{})
	var lines []string
	for i := 0; i < at.NumMethod(); i++ {
		m := at.Method(i)
		var params []string
		for j := 1; j < m.Type.NumIn(); j++ {
			params = append(params, fmt.Sprintf("a%d: %s", j, tsType(m.Type.In(j))))
		}
		ret := "void"
		for j := 0; j < m.Type.NumOut(); j++ {
			if o := m.Type.Out(j); o.Name() != "error" {
				ret = tsType(o)
				break
			}
		}
		lines = append(lines, fmt.Sprintf("  %s(%s): Promise<%s>;\n", m.Name, strings.Join(params, ", "), ret))
	}
	sort.Strings(lines)
	for _, l := range lines {
		b.WriteString(l)
	}
	b.WriteString("}\n")
	return b.String()
}

func TestBackendTypes(t *testing.T) {
	path := filepath.Join("..", "frontend", "src", "backend.d.ts")
	want := backendTypes()
	if os.Getenv("YACM_UPDATE_TYPES") != "" {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	// Git on Windows may check the file out with CRLF line ends.
	if err != nil || strings.ReplaceAll(string(got), "\r\n", "\n") != want {
		t.Fatalf("%s is out of date: run YACM_UPDATE_TYPES=1 go test -run TestBackendTypes .", path)
	}
}
